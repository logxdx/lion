#!/usr/bin/env python3
"""Generate src/unicode_tables.h from llama.cpp's src/unicode-data.cpp.

The tokenizer must classify code points and NFC-normalise exactly like the reference (KRAFTON llama.cpp), so the
tables are taken from its data file rather than from Python's unicodedata (whose Unicode version may differ).

    python3 tools/gen_unicode.py ~/llama.cpp/raon-src/src/unicode-data.cpp > src/unicode_tables.h
"""
import re
import sys

src = open(sys.argv[1], encoding='utf-8').read()


def block(name):
    m = re.search(r'\b' + name + r'\s*=\s*\{(.*?)\n\};', src, re.S)
    if not m:
        sys.exit('table not found: ' + name)
    return m.group(1)


def ints(s):
    return [int(x, 0) for x in re.findall(r'0x[0-9A-Fa-f]+|\b\d+\b', s.replace('ULL', ''))]


flags = re.findall(r'\{(0x[0-9A-Fa-f]+),\s*(0x[0-9A-Fa-f]+)\}', block('unicode_ranges_flags'))
flags = [(int(a, 16), int(b, 16)) for a, b in flags]
ws = sorted(ints(block('unicode_set_whitespace')))
ccc = sorted(tuple(ints(x)) for x in re.findall(r'\{([^{}]+)\}', block('unicode_combining_class')))
dec = sorted((int(a, 16), int(b, 16), int(c, 16)) for a, b, c in
             re.findall(r'\{(0x[0-9A-Fa-f]+),\s*\{(0x[0-9A-Fa-f]+),\s*(0x[0-9A-Fa-f]+)\}\}', block('unicode_decomposition')))
comp = sorted((int(a, 16), int(b, 16)) for a, b in
              re.findall(r'\{(0x[0-9A-Fa-f]+)ULL,\s*(0x[0-9A-Fa-f]+)\}', block('unicode_composition')))
assert flags[0][0] == 0 and flags[-1][0] == 0x110000


def emit(name, ctype, rows, per_line=6):
    out = ['static const %s %s[] = {' % (ctype, name)]
    for i in range(0, len(rows), per_line):
        out.append('    ' + ' '.join('{%s},' % ', '.join('0x%X' % v for v in r) for r in rows[i:i + per_line]))
    out.append('};')
    return '\n'.join(out)


print('// Generated by tools/gen_unicode.py from llama.cpp src/unicode-data.cpp. Do not edit.')
print('#pragma once')
print('#include <cstdint>')
print('namespace raon::uni {')
print('struct Range { uint32_t start; uint32_t flags; };            // flags hold until the next start')
print('struct Ccc { uint32_t cpt; uint32_t cls; };')
print('struct Dec { uint32_t cpt; uint32_t a; uint32_t b; };      // canonical decomposition, b = 0 if single')
print('struct Comp { uint64_t pair; uint32_t cpt; };               // (first << 32 | second) -> composite')
print(emit('k_flags', 'Range', flags))
print('static const uint32_t k_whitespace[] = {%s};' % ', '.join('0x%X' % v for v in ws))
print(emit('k_ccc', 'Ccc', ccc))
print(emit('k_dec', 'Dec', dec))
print(emit('k_comp', 'Comp', comp, 4))
print('}  // namespace raon::uni')
