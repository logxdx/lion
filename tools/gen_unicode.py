#!/usr/bin/env python3
"""Generate src/unicode_data.h from llama.cpp's src/unicode-data.cpp (MIT) so the
pre-tokenizer classifies code points exactly like llama.cpp does.
usage: gen_unicode.py <llama.cpp>/src/unicode-data.cpp > src/unicode_data.h"""
import re, sys
src = open(sys.argv[1]).read()
def block(name):
    i = src.index(name); j = src.index('{', src.index('=', i)); k = src.index('};', j)
    return src[j+1:k]
ranges = re.findall(r'\{0x([0-9A-Fa-f]+),\s*0x([0-9A-Fa-f]+)\}', block('unicode_ranges_flags'))
ws = re.findall(r'0x([0-9A-Fa-f]+)', block('unicode_set_whitespace'))
out = ['// generated by tools/gen_unicode.py from llama.cpp src/unicode-data.cpp (MIT) - do not edit',
       '#pragma once', '#include <cstdint>',
       f'static const uint32_t kUniRangeStart[{len(ranges)}] = {{']
out += [','.join(f'0x{int(a,16):X}' for a, _ in ranges[i:i+12]) + ',' for i in range(0, len(ranges), 12)]
out += ['};', f'static const uint16_t kUniRangeFlags[{len(ranges)}] = {{']
out += [','.join(f'0x{int(b,16):X}' for _, b in ranges[i:i+16]) + ',' for i in range(0, len(ranges), 16)]
out += ['};', f'static const int kUniRanges = {len(ranges)};',
        f'static const uint32_t kUniWhitespace[{len(ws)}] = {{' + ','.join(f'0x{int(w,16):X}' for w in sorted(ws, key=lambda x: int(x,16))) + '};',
        f'static const int kUniWhitespaceN = {len(ws)};']
print('\n'.join(out))
